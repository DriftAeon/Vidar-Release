use std::fs;
use std::path::Path;

/// Last path segment of every entry in the `generate_handler![...]` block of
/// src/main.rs. These are the app commands; Tauri ACL-checks them only when an
/// app manifest exists, so the list feeds `AppManifest::commands`.
fn handler_commands(src: &str) -> Vec<String> {
    let marker = "generate_handler![";
    let start = src
        .find(marker)
        .expect("build.rs: generate_handler![ block not found in src/main.rs")
        + marker.len();
    let end = src[start..]
        .find(']')
        .expect("build.rs: generate_handler! block is not closed")
        + start;
    let names: Vec<String> = src[start..end]
        .split(',')
        .map(|e| e.trim())
        .filter(|e| !e.is_empty())
        .map(|e| e.rsplit("::").next().unwrap_or(e).trim().to_string())
        .collect();
    assert!(
        !names.is_empty(),
        "build.rs: generate_handler! block parsed to zero commands"
    );
    names
}

fn main() {
    // tauri-build embeds icons/icon.ico as the exe icon but emits no
    // rerun-if-changed for it, so an icon swap alone never rebuilt the
    // resource. Cargo unions this with tauri's own.
    println!("cargo:rerun-if-changed=icons/icon.ico");
    println!("cargo:rerun-if-changed=src/main.rs");
    println!("cargo:rustc-check-cfg=cfg(falcon_shell)");

    // Marker embedded by src/build_guard.rs. Vidar has no feature of its own forwarding
    // custom-protocol, so CARGO_FEATURE_* cannot see it; tauri-build's is_dev() reads the
    // value tauri's build script exports (DEP_TAURI_DEV), i.e. !custom-protocol.
    let info = format!(
        "VIDAR-BUILD-INFO {{\"customProtocol\":{},\"optLevel\":\"{}\",\"debugAssertions\":{},\"profile\":\"{}\"}}\n",
        !tauri_build::is_dev(),
        std::env::var("OPT_LEVEL").unwrap_or_default(),
        std::env::var_os("CARGO_CFG_DEBUG_ASSERTIONS").is_some(),
        std::env::var("PROFILE").unwrap_or_default(),
    );
    let out = std::env::var("OUT_DIR").expect("build.rs: OUT_DIR unset");
    fs::write(Path::new(&out).join("build-info.txt"), info)
        .expect("build.rs: cannot write build-info.txt");

    let main_rs = fs::read_to_string("src/main.rs").expect("build.rs: cannot read src/main.rs");
    let names = handler_commands(&main_rs);

    // Generated permission set "main-all": every app command, for the main window.
    let mut toml = String::from(
        "# Generated by build.rs from the generate_handler! block in src/main.rs. Do not edit.\n\
         [[set]]\n\
         identifier = \"main-all\"\n\
         description = \"Every app command, granted to the main window\"\n\
         permissions = [\n",
    );
    for n in &names {
        toml.push_str(&format!("  \"allow-{}\",\n", n.replace('_', "-")));
    }
    toml.push_str("]\n");
    let dir = Path::new("permissions/sets");
    fs::create_dir_all(dir).expect("build.rs: cannot create permissions/sets");
    let file = dir.join("main-all.toml");
    if fs::read_to_string(&file).map(|c| c != toml).unwrap_or(true) {
        fs::write(&file, &toml).expect("build.rs: cannot write main-all.toml");
    }

    let leaked: Vec<&'static str> = names
        .into_iter()
        .map(|n| &*Box::leak(n.into_boxed_str()))
        .collect();
    let commands: &'static [&'static str] = Box::leak(leaked.into_boxed_slice());

    tauri_build::try_build(
        tauri_build::Attributes::new().app_manifest(
            tauri_build::AppManifest::new()
                .commands(commands)
                .permissions_path_pattern("./permissions/sets/*"),
        ),
    )
    .expect("tauri-build failed");
}
